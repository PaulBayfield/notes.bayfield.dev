export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function resolveLang(setting: "auto" | Lang): Lang {
  if (setting !== "auto") return setting;
  return navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function makeT(lang: Lang): Translate {
  return (key, vars) => {
    let s = strings[lang][key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export interface Formats {
  /** "3 minutes ago", "yesterday"… */
  relative: (iso: string | Date) => string;
  /** "12 March 2026 at 14:05" */
  dateTime: (iso: string | Date) => string;
}

export function makeFormats(lang: Lang): Formats {
  const locale = lang === "fr" ? "fr-FR" : "en-GB";
  const rtf = new Intl.RelativeTimeFormat(locale, { numeric: "auto" });
  const dtf = new Intl.DateTimeFormat(locale, { dateStyle: "long", timeStyle: "short" });
  const steps: [Intl.RelativeTimeFormatUnit, number][] = [
    ["second", 60],
    ["minute", 60],
    ["hour", 24],
    ["day", 7],
    ["week", 4.35],
    ["month", 12],
    ["year", Infinity],
  ];
  return {
    relative: (iso) => {
      let delta = (new Date(iso).getTime() - Date.now()) / 1000;
      if (Math.abs(delta) < 45) return rtf.format(0, "second");
      for (const [unit, size] of steps) {
        if (Math.abs(delta) < size) return rtf.format(Math.round(delta), unit);
        delta /= size;
      }
      return dtf.format(new Date(iso));
    },
    dateTime: (iso) => dtf.format(new Date(iso)),
  };
}
