// Generates src/lib/outlineIcons.ts: the icons Outline lets you pick for collections and
// documents, as static SVG, so the app doesn't need outline-icons (React 18 only) or Font Awesome.
//
// Run from a folder with the icon packages installed:
//   npm i outline-icons@^4.6 react@18 react-dom@18 @fortawesome/free-solid-svg-icons@^7 @fortawesome/free-brands-svg-icons@^7
//   node <this repo>/scripts/gen-outline-icons.mjs <outline repo>/shared/utils/IconLibrary.tsx <this repo>/src/lib/outlineIcons.ts

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const [libraryPath, outPath] = process.argv.slice(2);
const require = createRequire(path.join(process.cwd(), "index.js"));
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const outlineIcons = require("outline-icons");

const source = readFileSync(libraryPath, "utf8");
const icons = {};

// `name: { component: SomeIcon,` entries backed by outline-icons.
for (const [, name, component] of source.matchAll(/^\s{4}(\w+): \{\s*component: (\w+),/gm)) {
  const Component = outlineIcons[component];
  // LetterIcon (the collection's initial) is Outline's own component; the app draws that itself.
  if (!Component) continue;
  const svg = renderToStaticMarkup(React.createElement(Component, { color: "currentColor", size: 24 }));
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 24 24";
  const body = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  icons[name] = { viewBox, body };
}

// Font Awesome icons, keyed by their icon name ("dog", "rocket"…), drawn a bit smaller like Outline does.
for (const [, ident, pkg] of source.matchAll(/import \{ (fa\w+) \} from "@fortawesome\/(free-\w+-svg-icons)\/\w+";/g)) {
  const def = require(`@fortawesome/${pkg}/${ident}`)[ident];
  const [w, h, , , d] = def.icon;
  const paths = (Array.isArray(d) ? d : [d]).map((p) => `<path fill="currentColor" d="${p}"/>`).join("");
  icons[def.iconName] = { viewBox: `0 0 ${w} ${h}`, body: paths, fa: true };
}

const header = `// Generated by scripts/gen-outline-icons.mjs from Outline's IconLibrary. Do not edit.
// Icons: outline-icons (BSD-3-Clause) and Font Awesome Free (CC BY 4.0).

export interface OutlineIcon {
  viewBox: string;
  body: string;
  /** Font Awesome glyph: drawn at 2/3 size, like Outline. */
  fa?: boolean;
}

export const OUTLINE_ICONS: Record<string, OutlineIcon> = `;
writeFileSync(outPath, `${header}${JSON.stringify(icons, null, 0)};\n`);
console.log(`${Object.keys(icons).length} icons → ${outPath}`);
